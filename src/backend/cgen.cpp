void CCodeGen::visit(VariableDecl& node) {
    std::string cName = cIdent(node.name);

    // 数组声明
    if (!node.dimensions.empty()) {
        Vb6Type elemType = resolveArrayElemType(node.asType.get());
        std::string saElemType = mapSaElemType(elemType);
        std::string cType = "vb6_SafeArray1D*";

        // 前向声明 → .h
        if (node.access == AccessLevel::Public) {
            h_.emitLine("extern " + cType + " " + cName + ";");
        }

        // 数组创建代码
        // 目前只支持一维数组
        auto& dim = node.dimensions[0];
        std::string lBound = "0";
        std::string uBound = "0";
        if (dim.lower) {
            emitExpr(*dim.lower);
            lBound = std::move(lastExpr_);
        }
        if (dim.upper) {
            emitExpr(*dim.upper);
            uBound = std::move(lastExpr_);
        }

        std::string initCode = "vb6_SafeArrayCreate1D(" + saElemType + ", " + lBound + ", " + uBound + ")";
        if (node.access == AccessLevel::Public) {
            c_.emitLine(cType + " " + cName + " = " + initCode + ";");
        } else {
            c_.emitLine("static " + cType + " " + cName + " = " + initCode + ";");
        }

        // 注册到已知数组集合
        std::string lower = node.name;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
        knownArrays_.insert(lower);
        arrayElemTypes_[lower] = elemType;
        return;
    }

    // 动态数组声明: Dim arr() As Long → vb6_SafeArray1D* arr = NULL;
    if (node.isDynamicArray) {
        Vb6Type elemType = resolveArrayElemType(node.asType.get());
        std::string cType = "vb6_SafeArray1D*";

        if (node.access == AccessLevel::Public) {
            h_.emitLine("extern " + cType + " " + cName + ";");
            c_.emitLine(cType + " " + cName + " = NULL;");
        } else {
            c_.emitLine("static " + cType + " " + cName + " = NULL;");
        }

        // 注册到已知数组集合
        std::string lower = node.name;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
        knownArrays_.insert(lower);
        arrayElemTypes_[lower] = elemType;
        return;
    }

    std::string cType = mapTypeRef(node.asType.get());

    // 检查是否是类类型变量 → 注册到 knownClassVars_
    if (node.asType && node.asType->kind == ASTNodeKind::SimpleTypeRef) {
        auto& simple = static_cast<SimpleTypeRef&>(*node.asType);
        auto* clsSym = symTab_.lookupModule(simple.name);
        if (clsSym && clsSym->kind == SymbolKind::Class) {
            std::string lower = node.name;
            std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
            // P6.4: 接口类 → 注册到 knownIfaceVars_ (而非 knownClassVars_)
            if (clsSym->isInterface) {
                knownIfaceVars_[lower] = clsSym->name;
            } else {
                knownClassVars_.insert(lower);
            }
            // P6.5: WithEvents变量 → 注册到 knownWithEventsVars_
            if (node.isWithEvents) {
                knownWithEventsVars_[lower] = clsSym->name;
            }
        }
    }

    // 检查是否是Object类型变量 → 注册到 knownObjectVars_ (COM后期绑定)
    if (cType == "void*") {  // Object类型映射为void*
        std::string lower = node.name;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
        knownObjectVars_.insert(lower);
    }

    // P6.3: 检查是否是前期绑定COM变量 → 注册到 knownTypedComVars_
    if (node.asType && node.asType->kind == ASTNodeKind::SimpleTypeRef) {
        auto& simple = static_cast<SimpleTypeRef&>(*node.asType);
        auto* comSym = symTab_.lookupModule(simple.name);
        if (comSym && (comSym->kind == SymbolKind::ComClass || comSym->kind == SymbolKind::ComInterface)) {
            std::string lower = node.name;
            std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
            knownTypedComVars_[lower] = comSym;
            knownObjectVars_.erase(lower);  // 优先前期绑定
        }
    }

    // 记录double/single类型变量名 (用于Debug.Print浮点输出)
    if (cType == "double" || cType == "float") {
        std::string lower = node.name;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
        knownDoubleVars_.insert(lower);
    } else if (cType == "BSTR") {
        std::string lower = node.name;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
        knownBstrVars_.insert(lower);
    }

    // 前向声明 → .h, 定义 → .c
    if (node.access == AccessLevel::Public) {
        h_.emitLine("extern " + cType + " " + cName + ";");
    }

    // 变量定义 → .c
    // 类类型变量的默认值是NULL
    bool isClassType = false;
    bool isComIfaceType = false;
    bool isVb6IfaceType = false;  // P6.4: VB6接口引用类型
    if (node.asType && node.asType->kind == ASTNodeKind::SimpleTypeRef) {
        auto& simple = static_cast<SimpleTypeRef&>(*node.asType);
        auto* clsSym = symTab_.lookupModule(simple.name);
        isClassType = (clsSym && clsSym->kind == SymbolKind::Class && !clsSym->isInterface);
        isVb6IfaceType = (clsSym && clsSym->kind == SymbolKind::Class && clsSym->isInterface);
        isComIfaceType = (clsSym && (clsSym->kind == SymbolKind::ComClass || clsSym->kind == SymbolKind::ComInterface));
    }

    if (node.initializer) {
        emitExpr(*node.initializer);
        if (node.access == AccessLevel::Public) {
            c_.emitLine(cType + " " + cName + " = " + lastExpr_ + ";");
        } else {
            c_.emitLine("static " + cType + " " + cName + " = " + lastExpr_ + ";");
        }
    } else {
        // 判断是否是UDT类型 → 用 {0} 初始化
        bool isUdtType = false;
        if (node.asType && node.asType->kind == ASTNodeKind::SimpleTypeRef) {
            auto& simple = static_cast<SimpleTypeRef&>(*node.asType);
            auto* sym = symTab_.lookup(simple.name);
            isUdtType = (sym && sym->kind == SymbolKind::UserDefinedType);
        }
        std::string initVal;
        if (isClassType || isComIfaceType) {
            initVal = "NULL";
        } else if (isVb6IfaceType) {
            initVal = "{0}";  // P6.4: 接口引用 = {vtbl=NULL, obj=NULL}
        } else if (isUdtType) {
            initVal = "{0}";
        } else {
            initVal = defaultValue(
                node.asType ? typeSys_.resolveTypeName(static_cast<SimpleTypeRef*>(node.asType.get())->name) : Vb6Type::Variant
            );
        }
        if (node.access == AccessLevel::Public) {
            c_.emitLine(cType + " " + cName + " = " + initVal + ";");
        } else {
            c_.emitLine("static " + cType + " " + cName + " = " + initVal + ";");
        }
    }
}

void CCodeGen::visit(DeclareDecl& node) {
    // 外部函数声明 (Declare Sub/Function ... Lib "xxx" [Alias "yyy"] [CDecl])
    std::string retType = (node.procKind == ProcKind::Function)
        ? mapTypeRef(node.returnType.get()) : "void";

    std::string params = makeParamList(node.params);
    if (params.empty()) params = "void";

    // 调用约定
    std::string callConv = (node.callingConv == CallConv::CDecl) ? "__cdecl" : "__stdcall";

    // 去除字符串两端引号 (词法器保留引号)
    auto stripQuotes = [](const std::string& s) -> std::string {
        if (s.size() >= 2 && s.front() == '"' && s.back() == '"')
            return s.substr(1, s.size() - 2);
        return s;
    };

    // Lib名: 去引号、去.dll后缀
    std::string libName = stripQuotes(node.libName);
    if (libName.size() > 4 &&
        (libName.compare(libName.size()-4, 4, ".dll") == 0 ||
         libName.compare(libName.size()-4, 4, ".DLL") == 0)) {
        libName = libName.substr(0, libName.size()-4);
    }

    // Alias: 去引号, 保持原始导出名 (大小写敏感, 可能含#序号前缀)
    std::string aliasName = stripQuotes(node.aliasName);

    // VB6函数名→C标识符 (用于调用点)
    std::string cFuncIdent = cIdent(node.name);

    // 导出名: Alias优先, 否则用VB6函数名
    // 注意: Windows API函数名是大小写敏感的, 需要保持原始大小写
    std::string exportedName = aliasName.empty() ? node.name : aliasName;

    // 生成: #pragma comment(lib, "xxx.lib")
    c_.emitLine("#pragma comment(lib, \"" + libName + ".lib\")");

    // 生成DLL导入声明 + 名称映射
    if (exportedName != cFuncIdent) {
        // 导出名≠VB6名: 声明导出名, 用#define映射
        h_.emitLine("__declspec(dllimport) " + retType + " " + callConv + " " + exportedName + "(" + params + ");");
        h_.emitLine("#define " + cFuncIdent + " " + exportedName);
    } else {
        // 导出名=VB6名: 直接声明
        h_.emitLine("__declspec(dllimport) " + retType + " " + callConv + " " + exportedName + "(" + params + ");");
    }
}

void CCodeGen::visit(PropertyDecl& node) {
    // Property Get/Let/Set → C函数
    // 类模块: 第一个参数为 me 指针
    std::string sig = makePropertySignature(node);
    c_.emitLine(sig + " {");

    // Property Get: 设置返回值变量 (与Function相同语义)
    if (node.propKind == ProcKind::PropertyGet) {
        currentReturnVar_ = "vb6_ret_" + cIdent(node.name);
        if (node.returnType) {
            std::string retType = mapTypeRef(node.returnType.get());
            Vb6Type retVb6Type = typeSys_.resolveTypeName(
                static_cast<SimpleTypeRef*>(node.returnType.get())->name);
            c_.emitLine(retType + " " + currentReturnVar_ + " = " + defaultValue(retVb6Type) + ";");
        }
    }

    if (!node.body.empty()) {
        c_.indent();
        // 类模块: 设置当前me变量为第一个参数
        if (isClassModule_) {
            // 在类方法中, 模块级变量引用需通过 me-> 前缀
            // 这通过 visit(IdentifierExpr) 和 visit(AssignmentStmt) 处理
        }
        emitStmtList(node.body);

        // Property Get: 隐式返回 vb6_ret_<propName>
        if (node.propKind == ProcKind::PropertyGet && node.returnType) {
            c_.emitLine("return " + currentReturnVar_ + ";");
        }
        c_.dedent();
    }

    // 清理返回值变量
    if (node.propKind == ProcKind::PropertyGet) {
        currentReturnVar_ = "";
    }

    c_.emitLine("}");
    c_.emitBlank();
}

void CCodeGen::visit(EventDecl& node) {
    // P6.5: Event声明 → 回调函数指针typedef在emitEventSink中统一生成
    // 此处仅生成注释标记
    c_.emitLine("/* Event " + node.name + " — callback typedef in event sink table */");
}

// ============================================================
// Property签名生成
// ============================================================

std::string CCodeGen::makePropertySignature(PropertyDecl& node) {
    // Property Get/Let/Set使用不同前缀: prop_get_/prop_let_/prop_set_
    // 避免同名Property在C层面链接冲突
    std::string prefix;
    switch (node.propKind) {
        case ProcKind::PropertyGet:  prefix = "prop_get_"; break;
        case ProcKind::PropertyLet:  prefix = "prop_let_"; break;
        case ProcKind::PropertySet:  prefix = "prop_set_"; break;
        default:                     prefix = "prop_get_"; break;
    }
    std::string propName = cProcName(prefix + node.name, node.access);
    std::string params;

    // 类模块: 第一个参数为 me 指针
    if (isClassModule_) {
        params = classMeParam();
        if (!node.params.empty()) params += ", ";
    }

    // 空参数列表: 类模块已有me参数时不需要"void"
    if (node.params.empty() && isClassModule_) {
        // params已经有me, 不追加
    } else {
        params += makeParamList(node.params);
    }

    switch (node.propKind) {
        case ProcKind::PropertyGet: {
            std::string retType = node.returnType ? mapTypeRef(node.returnType.get()) : "vb6_VARIANT";
            return retType + " " + propName + "(" + params + ")";
        }
        case ProcKind::PropertyLet: {
            // VB6: Property Let Name(v) — 最后一个参数v就是赋值值
            // 不追加额外的vb6_let_value参数
            return "void " + propName + "(" + params + ")";
        }
        case ProcKind::PropertySet: {
            // VB6: Property Set Name(v) — 最后一个参数v就是对象引用
            return "void " + propName + "(" + params + ")";
        }
        default:
            return "void " + propName + "(" + params + ")";
    }
}

// ============================================================
// 类工厂函数生成
// ============================================================

std::string CCodeGen::classMeParam() const {
    std::string clsStruct = "vb6_cls_" + cIdent(baseName_);
    return clsStruct + "* me";
}

void CCodeGen::emitClassFactory(Module& module) {
    std::string clsStruct = "vb6_cls_" + cIdent(baseName_);

    c_.emitBlank();
    c_.emitLine("// === 类工厂函数: " + module.moduleName + " ===");
    c_.emitBlank();

    // _New: 分配+初始化
    c_.emitLine(clsStruct + "* " + clsStruct + "_New(void) {");
    c_.indent();
    c_.emitLine(clsStruct + "* me = (" + clsStruct + "*)vb6_Alloc(sizeof(" + clsStruct + "));");
    c_.emitLine("if (!me) return NULL;");

    // 初始化所有字段为默认值
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::VariableDecl) {
            auto& var = static_cast<VariableDecl&>(*decl);
            std::string field = cIdent(var.name);
            if (var.isDynamicArray || !var.dimensions.empty()) {
                c_.emitLine("me->" + field + " = NULL;");
            } else if (var.asType) {
                c_.emitLine("me->" + field + " = " + defaultValue(resolveArrayElemType(var.asType.get())) + ";");
            } else {
                c_.emitLine("me->" + field + " = 0;");
            }
        }
    }

    // P6.5: 初始化事件接收器指针为NULL
    bool hasEvents = false;
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::EventDecl) { hasEvents = true; break; }
    }
    if (hasEvents) {
        c_.emitLine("me->events = NULL;  /* P6.5: no event sink initially */");
    }

    // 检查是否有 Class_Initialize 方法
    bool hasInit = false;
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::SubDecl) {
            auto& sub = static_cast<SubDecl&>(*decl);
            if (sub.name == "Class_Initialize") {
                hasInit = true;
                c_.emitLine(cProcName("Class_Initialize", sub.access) + "(me);");
                break;
            }
        }
    }

    c_.emitLine("return me;");
    c_.dedent();
    c_.emitLine("}");

    // _Destroy: 终止+释放
    c_.emitBlank();
    c_.emitLine("void " + clsStruct + "_Destroy(" + clsStruct + "* me) {");
    c_.indent();
    c_.emitLine("if (!me) return;");

    // 检查是否有 Class_Terminate 方法
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::SubDecl) {
            auto& sub = static_cast<SubDecl&>(*decl);
            if (sub.name == "Class_Terminate") {
                c_.emitLine(cProcName("Class_Terminate", sub.access) + "(me);");
                break;
            }
        }
    }

    // 释放BSTR字段
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::VariableDecl) {
            auto& var = static_cast<VariableDecl&>(*decl);
            Vb6Type varType = var.asType ? resolveArrayElemType(var.asType.get()) : Vb6Type::Variant;
            if (varType == Vb6Type::String) {
                c_.emitLine("vb6_BSTR_Free(me->" + cIdent(var.name) + ");");
            } else if (var.isDynamicArray || !var.dimensions.empty()) {
                c_.emitLine("if (me->" + cIdent(var.name) + ") vb6_SA_Destroy(me->" + cIdent(var.name) + ");");
            }
        }
    }

    c_.emitLine("vb6_Free(me);");
    c_.dedent();
    c_.emitLine("}");
}

// ============================================================
// P6.4: 接口 vtable + 包装类型生成 (Implements 代码生成)
// ============================================================

void CCodeGen::emitInterfaceVtable(Module& module) {
    std::string clsStruct = "vb6_cls_" + cIdent(baseName_);

    for (auto& impl : module.implements) {
        const std::string& ifaceName = impl->interfaceName;
        std::string ifaceId = cIdent(ifaceName);

        // 收集接口方法信息: 从实现类中查找 IFoo_MethodName 方法
        struct IfaceMethodInfo {
            std::string methodName;   // 原始方法名 (如 "Bar")
            std::string implFuncName; // 实现函数C名 (如 "vb6_Class1_IFoo_Bar")
            std::string retType;      // 返回C类型
            std::string params;       // 参数列表 (不含me, 如 "int32_t x")
            bool isSub;               // Sub vs Function
        };
        std::vector<IfaceMethodInfo> methods;

        for (auto& decl : module.declarations) {
            if (decl->kind == ASTNodeKind::SubDecl) {
                auto& sub = static_cast<SubDecl&>(*decl);
                // 检查是否为 Implements 实现方法 (IFoo_MethodName 格式)
                if (sub.name.size() > ifaceName.size() + 1 &&
                    Symbol::toLower(sub.name.substr(0, ifaceName.size() + 1)) ==
                    Symbol::toLower(ifaceName + "_")) {
                    std::string methodName = sub.name.substr(ifaceName.size() + 1);
                    std::string params = makeParamList(sub.params);
                    methods.push_back({methodName, cProcName(sub.name, sub.access),
                                       "void", params, true});
                }
            } else if (decl->kind == ASTNodeKind::FunctionDecl) {
                auto& func = static_cast<FunctionDecl&>(*decl);
                if (func.name.size() > ifaceName.size() + 1 &&
                    Symbol::toLower(func.name.substr(0, ifaceName.size() + 1)) ==
                    Symbol::toLower(ifaceName + "_")) {
                    std::string methodName = func.name.substr(ifaceName.size() + 1);
                    std::string params = makeParamList(func.params);
                    std::string retType = mapTypeRef(func.returnType.get());
                    methods.push_back({methodName, cProcName(func.name, func.access),
                                       retType, params, false});
                }
            } else if (decl->kind == ASTNodeKind::PropertyDecl) {
                auto& prop = static_cast<PropertyDecl&>(*decl);
                if (prop.name.size() > ifaceName.size() + 1 &&
                    Symbol::toLower(prop.name.substr(0, ifaceName.size() + 1)) ==
                    Symbol::toLower(ifaceName + "_")) {
                    std::string methodName = prop.name.substr(ifaceName.size() + 1);
                    std::string params = makeParamList(prop.params);
                    // Property Get → Function, Property Let/Set → Sub
                    // 使用prop_get_/prop_let_/prop_set_前缀
                    std::string propPrefix;
                    if (prop.propKind == ProcKind::PropertyGet) {
                        propPrefix = "prop_get_";
                        std::string retType = mapTypeRef(prop.returnType.get());
                        methods.push_back({methodName, cProcName(propPrefix + prop.name, prop.access),
                                           retType, params, false});
                    } else {
                        propPrefix = (prop.propKind == ProcKind::PropertySet) ? "prop_set_" : "prop_let_";
                        methods.push_back({methodName, cProcName(propPrefix + prop.name, prop.access),
                                           "void", params, true});
                    }
                }
            }
        }

        if (methods.empty()) continue;

        // 1. 生成 vtable 结构体 (函数指针表)
        std::string vtblName = "vb6_vtbl_" + ifaceId;
        h_.emitLine("// Interface vtable: " + ifaceName);
        h_.emitLine("typedef struct " + vtblName + " {");
        for (auto& m : methods) {
            std::string paramList = classMeParam();
            if (m.params != "void") {
                paramList += ", " + m.params;
            }
            h_.emitLine("    " + m.retType + " (*" + cIdent(m.methodName) + ")(" + paramList + ");");
        }
        h_.emitLine("} " + vtblName + ";");
        h_.emitBlank();

        // 2. 生成接口引用包装类型 (vtable指针 + 对象指针)
        std::string ifaceTypeName = "vb6_iface_" + ifaceId;
        h_.emitLine("typedef struct " + ifaceTypeName + " {");
        h_.emitLine("    " + vtblName + "* vtbl;");
        h_.emitLine("    void* obj;");
        h_.emitLine("} " + ifaceTypeName + ";");
        h_.emitBlank();

        // 3. 生成全局 vtable 实例 (指向实现类的接口方法)
        std::string vtblInstance = vtblName + "_for_" + cIdent(baseName_);
        c_.emitBlank();
        c_.emitLine("// Interface vtable instance: " + ifaceName + " for " + module.moduleName);
        c_.emitLine("static " + vtblName + " " + vtblInstance + " = {");
        c_.indent();
        for (size_t i = 0; i < methods.size(); i++) {
            std::string entry = "." + cIdent(methods[i].methodName) + " = " + methods[i].implFuncName;
            if (i < methods.size() - 1) entry += ",";
            c_.emitLine(entry);
        }
        c_.dedent();
        c_.emitLine("};");

        // 4. 生成包装函数: vb6_iface_IFoo_wrap(obj) → 创建接口引用
        h_.emitLine(ifaceTypeName + " " + ifaceTypeName + "_wrap(" + clsStruct + "* obj);");
        h_.emitBlank();
        c_.emitBlank();
        c_.emitLine(ifaceTypeName + " " + ifaceTypeName + "_wrap(" + clsStruct + "* obj) {");
        c_.indent();
        c_.emitLine(ifaceTypeName + " iface;");
        c_.emitLine("iface.vtbl = &" + vtblInstance + ";");
        c_.emitLine("iface.obj = obj;");
        c_.emitLine("return iface;");
        c_.dedent();
        c_.emitLine("}");
    }
}

// ============================================================
// P6.5: RaiseEvent语句 → 生成事件回调分发代码
// ============================================================

void CCodeGen::visit(RaiseEventStmt& node) {
    // RaiseEvent EventName(args...)
    // 生成: if (me->events && me->events->onEventName) { me->events->onEventName(me->events->handler, args...); }
    std::string evtId = cIdent(node.eventName);
    std::string callbackName = "on" + evtId;  // 事件接收器中的回调字段名

    c_.emitLine("if (me->events && me->events->" + callbackName + ") {");
    c_.indent();
    // 生成回调调用
    std::string call = "me->events->" + callbackName + "(me->events->handler";
    for (size_t i = 0; i < node.args.size(); i++) {
        emitExpr(*node.args[i]);
        call += ", " + lastExpr_;
    }
    call += ");";
    c_.emitLine(call);
    c_.dedent();
    c_.emitLine("}");
}

void CCodeGen::visit(BeepStmt& node) {
    c_.emitLine("vb6_Beep();");
}

void CCodeGen::visit(DoEventsStmt& node) {
    c_.emitLine("vb6_DoEvents();");
}

// ============================================================
// P6.5: 事件接收器表生成 (Event Sink Table)
// ============================================================

void CCodeGen::emitEventSink(Module& module) {
    std::string clsStruct = "vb6_cls_" + cIdent(baseName_);
    std::string sinkName = "vb6_events_" + cIdent(baseName_);

    // 收集所有Event声明
    struct EventInfo {
        std::string name;           // 事件名(原始)
        std::string cName;          // 安全C标识符
        std::vector<ParameterInfo> params;  // 事件参数
    };
    std::vector<EventInfo> events;

    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::EventDecl) {
            auto& evt = static_cast<EventDecl&>(*decl);
            EventInfo info;
            info.name = evt.name;
            info.cName = cIdent(evt.name);
            for (auto& param : evt.params) {
                ParameterInfo pi;
                pi.name = param->name;
                // 用mapTypeRef获取C类型, 同时从TypeSystem获取Vb6Type
                std::string cType = mapTypeRef(param->asType.get());
                pi.type = (param->asType && param->asType->kind == ASTNodeKind::SimpleTypeRef)
                    ? typeSys_.resolveTypeName(static_cast<SimpleTypeRef*>(param->asType.get())->name)
                    : Vb6Type::Variant;
                if (pi.type == Vb6Type::Unknown || pi.type == Vb6Type::Empty)
                    pi.type = Vb6Type::Variant;
                // 事件参数总是ByVal传递(跨对象边界)
                pi.isByVal = true;
                info.params.push_back(pi);
            }
            events.push_back(std::move(info));
        }
    }

    if (events.empty()) return;

    // 1. 生成事件回调函数指针typedef
    h_.emitLine("// P6.5: Event callback function pointer types");
    for (auto& evt : events) {
        std::string cbName = "vb6_evt_" + evt.cName + "_cb";
        std::string sig = "void (*" + cbName + ")(void* handler";
        for (auto& p : evt.params) {
            sig += ", " + mapType(p.type) + " " + cIdent(p.name);
        }
        sig += ")";
        h_.emitLine("typedef " + sig + ";");
    }
    h_.emitBlank();

    // 2. 生成事件接收器表结构体
    h_.emitLine("// Event sink table: " + module.moduleName);
    h_.emitLine("typedef struct " + sinkName + " {");
    h_.emitLine("    void* handler;  /* event handler object (consumer) */");
    for (auto& evt : events) {
        std::string cbName = "vb6_evt_" + evt.cName + "_cb";
        h_.emitLine("    " + cbName + " on" + evt.cName + ";  /* Event " + evt.name + " */");
    }
    h_.emitLine("} " + sinkName + ";");
    h_.emitBlank();
}

