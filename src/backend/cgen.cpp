// ============================================================
// 主入口: 生成 .h + .c
// ============================================================

bool CCodeGen::generate(Module& module, const std::string& baseName,
                         const std::unordered_set<std::string>& externalModules) {
    currentModule_ = &module;
    baseName_ = baseName;
    moduleName_ = baseName;  // 模块名 = 输出基名（如 "MathUtils"）
    isMultiModule_ = !externalModules.empty();  // 有外部依赖 = 多模块项目
    emittedSymbols_.clear();
    labelCounter_ = 0;
    tempCounter_ = 0;

    // 生成 .h 头文件
    std::string guard = "VB6CGEN_" + cIdent(baseName_) + "_H";
    std::transform(guard.begin(), guard.end(), guard.begin(), ::toupper);

    h_.emitLine("// Generated by vb6c3 (c3.exe) from " + module.filename);
    h_.emitLine("#ifndef " + guard);
    h_.emitLine("#define " + guard);
    h_.emitBlank();
    h_.emitLine("#include <stdint.h>");
    h_.emitLine("#include <stddef.h>");
    h_.emitLine("#include <stdbool.h>");
    h_.emitLine("#include <wchar.h>");
    h_.emitLine("#include \"vb6rtl.h\"");
    // 跨模块 #include: 引用外部模块的头文件
    for (const auto& extMod : externalModules) {
        h_.emitLine("#include \"" + extMod + ".h\"");
    }
    h_.emitBlank();

    // 生成 .c 源文件头
    c_.emitLine("// Generated by vb6c3 (c3.exe) from " + module.filename);
    c_.emitLine("#include \"" + baseName_ + ".h\"");
    c_.emitBlank();

    // === 第一遍: 声明 (前向声明 → .h, 定义 → .c) ===

    // 模块级声明: 枚举、类型、常量、变量、过程
    // 按类别有序输出, 确保C编译器能看到前向声明

    // 1. Enum定义 (必须最先, 因为常量可能引用枚举值)
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::EnumDecl) {
            visit(static_cast<EnumDecl&>(*decl));
        }
    }

    // 2. Type定义
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::TypeDecl) {
            visit(static_cast<TypeDecl&>(*decl));
        }
    }

    // 3. Const
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::ConstDecl) {
            visit(static_cast<ConstDecl&>(*decl));
        }
    }

    // 4. 变量声明 (前向声明 → .h, 定义 → .c)
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::VariableDecl) {
            visit(static_cast<VariableDecl&>(*decl));
        }
    }

    // 5. Declare (外部函数声明)
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::DeclareDecl) {
            visit(static_cast<DeclareDecl&>(*decl));
        }
    }

    // 6. 过程前向声明 → .h
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::SubDecl) {
            auto& sub = static_cast<SubDecl&>(*decl);
            std::string sig = makeProcSignature(sub);
            if (sub.access == AccessLevel::Public) {
                h_.emitLine(sig + ";");
            } else {
                h_.emitLine("static " + sig + ";");
            }
        } else if (decl->kind == ASTNodeKind::FunctionDecl) {
            auto& func = static_cast<FunctionDecl&>(*decl);
            std::string sig = makeProcSignature(func);
            if (func.access == AccessLevel::Public) {
                h_.emitLine(sig + ";");
            } else {
                h_.emitLine("static " + sig + ";");
            }
        }
    }

    h_.emitBlank();
    h_.emitLine("#endif /* " + guard + " */");

    // === 第二遍: 过程体 → .c ===
    c_.emitBlank();
    c_.emitLine("// === 过程实现 ===");
    c_.emitBlank();

    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::SubDecl) {
            visit(static_cast<SubDecl&>(*decl));
        } else if (decl->kind == ASTNodeKind::FunctionDecl) {
            visit(static_cast<FunctionDecl&>(*decl));
        }
    }

    // 生成入口点
    c_.emitBlank();
    c_.emitLine("// === 入口点 ===");
    bool hasMain = false;
    std::string firstPublicSub;  // 备用入口：首个Public Sub
    for (auto& decl : module.declarations) {
        if (decl->kind == ASTNodeKind::SubDecl) {
            auto& sub = static_cast<SubDecl&>(*decl);
            if (sub.name == "Main" && sub.access == AccessLevel::Public) {
                hasMain = true;
            } else if (sub.access == AccessLevel::Public && firstPublicSub.empty()) {
                firstPublicSub = sub.name;
            }
        }
    }
    if (hasMain) {
        c_.emitLine("int main(int argc, char* argv[]) {");
        c_.indent();
        c_.emitLine("vb6_Init();");
        c_.emitLine(cProcName("Main", AccessLevel::Public) + "();");
        c_.emitLine("vb6_Exit();");
        c_.emitLine("return 0;");
        c_.dedent();
        c_.emitLine("}");
    } else if (!firstPublicSub.empty()) {
        // 无 Sub Main 时自动调用首个 Public Sub
        c_.emitLine("int main(int argc, char* argv[]) {");
        c_.indent();
        c_.emitLine("vb6_Init();");
        c_.emitLine(cProcName(firstPublicSub, AccessLevel::Public) + "();");
        c_.emitLine("vb6_Exit();");
        c_.emitLine("return 0;");
        c_.dedent();
        c_.emitLine("}");
    } else {
        c_.emitLine("// No Public Sub found - no entry point generated");
    }

    // 保存生成结果
    header_ = h_.str();
    source_ = c_.str();

    currentModule_ = nullptr;
    return diag_.errorCount() == 0;
}

// ============================================================
// 类型映射
// ============================================================

std::string CCodeGen::mapType(Vb6Type type) const {
    // 检查数组标志
    bool isArray = (static_cast<uint16_t>(type) & static_cast<uint16_t>(Vb6Type::Array)) != 0;
    Vb6Type baseType = isArray
        ? static_cast<Vb6Type>(static_cast<uint16_t>(type) & ~static_cast<uint16_t>(Vb6Type::Array))
        : type;

    std::string cType;
    switch (baseType) {
        case Vb6Type::Empty:    cType = "int16_t"; break;   // VB6 Empty = 0
        case Vb6Type::Null:     cType = "int16_t"; break;   // VB6 Null = 1
        case Vb6Type::Integer:  cType = "int16_t"; break;
        case Vb6Type::Long:     cType = "int32_t"; break;
        case Vb6Type::Single:   cType = "float"; break;
        case Vb6Type::Double:   cType = "double"; break;
        case Vb6Type::Currency: cType = "int64_t"; break;   // scaled integer
        case Vb6Type::Date:     cType = "double"; break;    // OLE date
        case Vb6Type::String:   cType = "BSTR"; break;      // wchar_t* wrapper
        case Vb6Type::Object:   cType = "void*"; break;     // IDispatch* → void* for now
        case Vb6Type::Error:    cType = "int32_t"; break;   // SCODE/HRESULT
        case Vb6Type::Boolean:  cType = "int16_t"; break;   // VB6: True=-1, False=0
        case Vb6Type::Variant:  cType = "VARIANT"; break;   // tagged union
        case Vb6Type::Byte:     cType = "uint8_t"; break;
        case Vb6Type::ULong:    cType = "uint32_t"; break;
        case Vb6Type::Void:     cType = "void"; break;
        case Vb6Type::Decimal:  cType = "VARIANT"; break;   // 用VARIANT兜底
        case Vb6Type::UserDefinedType: cType = "VARIANT"; break; // 占位, 后续改进
        default:                cType = "VARIANT"; break;    // 未知/安全兜底
    }

    if (isArray) {
        cType = "vb6_SafeArray1D*";  // 数组用SAFEARRAY
    }
    return cType;
}

std::string CCodeGen::mapTypeRef(ASTNode* typeRef) const {
    if (!typeRef) return "VARIANT";  // 未指定类型 = Variant

    switch (typeRef->kind) {
        case ASTNodeKind::SimpleTypeRef: {
            auto& simple = static_cast<SimpleTypeRef&>(*typeRef);
            // 尝试从类型系统解析
            Vb6Type t = typeSys_.resolveTypeName(simple.name);
            if (t != Vb6Type::Unknown) {
                return mapType(t);
            }
            // 可能是用户定义类型
            return cIdent(simple.name);
        }
        case ASTNodeKind::ArrayTypeRef:
            return "vb6_SafeArray1D*";  // SAFEARRAY指针
        case ASTNodeKind::FixedStringTypeRef:
            return "BSTR";
        default:
            return "VARIANT";
    }
}

std::string CCodeGen::defaultValue(Vb6Type type) const {
    switch (type) {
        case Vb6Type::Integer:
        case Vb6Type::Long:
        case Vb6Type::Byte:
        case Vb6Type::Boolean:
        case Vb6Type::Error:
            return "0";
        case Vb6Type::Single:
        case Vb6Type::Double:
        case Vb6Type::Date:
            return "0.0";
        case Vb6Type::Currency:
            return "0LL";
        case Vb6Type::String:
            return "vb6_BSTR_Empty()";
        case Vb6Type::Object:
            return "NULL";
        case Vb6Type::Variant:
        case Vb6Type::Empty:
        case Vb6Type::Null:
            return "vb6_VariantEmpty()";
        default:
            return "vb6_VariantEmpty()";
    }
}

// ============================================================
// 标识符命名
// ============================================================

std::string CCodeGen::cIdent(const std::string& vb6Name) const {
    // VB6标识符可能含C关键字冲突, 添加前缀
    static const std::unordered_set<std::string> cKeywords = {
        "auto", "break", "case", "char", "const", "continue", "default", "do",
        "double", "else", "enum", "extern", "float", "for", "goto", "if",
        "int", "long", "register", "return", "short", "signed", "sizeof",
        "static", "struct", "switch", "typedef", "union", "unsigned", "void",
        "volatile", "while", "bool", "true", "false", "NULL",
        // C99/C11
        "inline", "restrict", "_Bool", "_Complex", "_Imaginary",
        // MSVC扩展
        "cdecl", "stdcall", "declspec", "dllimport", "dllexport",
    };

    std::string name = vb6Name;

    // 替换VB6方括号标识符 [Name] → Name
    if (!name.empty() && name.front() == '[' && name.back() == ']') {
        name = name.substr(1, name.size() - 2);
    }

    // 如果是C关键字, 添加vb6_前缀
    std::string lower = name;
    std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);
    if (cKeywords.count(lower)) {
        return "vb6_" + name;
    }

    return name;
}

std::string CCodeGen::cProcName(const std::string& procName, AccessLevel access,
                                 const std::string& sourceModule) const {
    // 跨模块函数(外部符号): vb6_<ModuleName>_<ProcName>
    if (!sourceModule.empty()) {
        return "vb6_" + cIdent(sourceModule) + "_" + cIdent(procName);
    }
    // 多模块项目本模块 Public 函数: vb6_<ModuleName>_<ProcName>
    // （Private 函数只在本模块内可见，不需要模块前缀）
    // 单模块项目: vb6_<ProcName> (保持向后兼容)
    if (isMultiModule_ && access == AccessLevel::Public && !moduleName_.empty()) {
        return "vb6_" + cIdent(moduleName_) + "_" + cIdent(procName);
    }
    return "vb6_" + cIdent(procName);
}

// ============================================================
// 表达式求值 (累加器模式: lastExpr_接收结果)
// ============================================================

void CCodeGen::emitExpr(Expr& expr) {
    switch (expr.kind) {
        case ASTNodeKind::LiteralExpr:
            visit(static_cast<LiteralExpr&>(expr)); break;
        case ASTNodeKind::IdentifierExpr:
            visit(static_cast<IdentifierExpr&>(expr)); break;
        case ASTNodeKind::BinaryExpr:
            visit(static_cast<BinaryExpr&>(expr)); break;
        case ASTNodeKind::UnaryExpr:
            visit(static_cast<UnaryExpr&>(expr)); break;
        case ASTNodeKind::MemberAccessExpr:
            visit(static_cast<MemberAccessExpr&>(expr)); break;
        case ASTNodeKind::DictionaryAccessExpr:
            visit(static_cast<DictionaryAccessExpr&>(expr)); break;
        case ASTNodeKind::IndexOrCallExpr:
            visit(static_cast<IndexOrCallExpr&>(expr)); break;
        case ASTNodeKind::NewExpr:
            visit(static_cast<NewExpr&>(expr)); break;
        case ASTNodeKind::TypeOfExpr:
            visit(static_cast<TypeOfExpr&>(expr)); break;
        case ASTNodeKind::AddressOfExpr:
            visit(static_cast<AddressOfExpr&>(expr)); break;
        case ASTNodeKind::MeExpr:
            visit(static_cast<MeExpr&>(expr)); break;
        case ASTNodeKind::WithMemberExpr:
            visit(static_cast<WithMemberExpr&>(expr)); break;
        default:
            lastExpr_ = "/* unknown expr */";
            break;
    }
}

// ============================================================
// 表达式 visit 方法
// ============================================================

void CCodeGen::visit(LiteralExpr& node) {
    switch (node.literalKind) {
        case LiteralKind::Integer:
            lastExpr_ = std::to_string(static_cast<int>(node.intValue));
            break;
        case LiteralKind::Long:
            lastExpr_ = std::to_string(node.longValue) + "L";
            break;
        case LiteralKind::Single:
            lastExpr_ = std::to_string(node.floatValue) + "f";
            break;
        case LiteralKind::Double:
        case LiteralKind::Currency:
        case LiteralKind::Decimal:
            lastExpr_ = std::to_string(node.doubleValue);
            break;
        case LiteralKind::String: {
            // VB6字符串 → C宽字符串字面量 L"..."
            // rawText包含引号, 需要strip
            std::string inner = node.rawText;
            if (inner.size() >= 2 && inner.front() == '"' && inner.back() == '"') {
                inner = inner.substr(1, inner.size() - 2);
            }
            // VB6的""转义 (双引号在字符串内) → C的\"转义
            // 同时转义反斜杠
            std::string escaped;
            escaped.reserve(inner.size() + 4);
            for (size_t j = 0; j < inner.size(); j++) {
                char ch = inner[j];
                if (ch == '"') {
                    // VB6中""表示引号内的一个", 已被lexer解码为单个"
                    escaped += "\\\"";
                } else if (ch == '\\') {
                    escaped += "\\\\";
                } else if (ch == '\n') {
                    escaped += "\\n";
                } else if (ch == '\r') {
                    escaped += "\\r";
                } else if (ch == '\t') {
                    escaped += "\\t";
                } else {
                    escaped += ch;
                }
            }
            lastExpr_ = "vb6_BSTR_FromStr(L\"" + escaped + "\")";
            break;
        }
        case LiteralKind::Boolean:
            lastExpr_ = node.boolValue ? "(-1)" : "0";  // VB6: True=-1
            break;
        case LiteralKind::Nothing:
            lastExpr_ = "NULL";
            break;
        case LiteralKind::Empty:
            lastExpr_ = "vb6_VariantEmpty()";
            break;
        case LiteralKind::Null:
            lastExpr_ = "vb6_VariantNull()";
            break;
        case LiteralKind::Date:
            lastExpr_ = std::to_string(node.doubleValue);  // OLE date as double
            break;
    }
}

void CCodeGen::visit(IdentifierExpr& node) {
    // 查找符号确定类型
    std::string cName = cIdent(node.name);

    // 内置对象特殊处理
    std::string lower = node.name;
    std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);

    if (lower == "me") {
        lastExpr_ = "vb6_Me";
        return;
    }

    // 检查是否是当前函数名 (Function返回值赋值 = 设置返回变量)
    if (currentProc_ && lower == Symbol::toLower(currentProc_->name)
        && currentProc_->kind == SymbolKind::Function) {
        lastExpr_ = currentReturnVar_;
        return;
    }

    // 内置常量/枚举映射
    if (lower == "vbokonly")       { lastExpr_ = "0"; return; }
    if (lower == "vbcancel")       { lastExpr_ = "2"; return; }
    if (lower == "vbabortretryignore") { lastExpr_ = "2"; return; }
    if (lower == "vbyesnocancel")  { lastExpr_ = "3"; return; }
    if (lower == "vbyesno")        { lastExpr_ = "4"; return; }
    if (lower == "vbretrycancel")  { lastExpr_ = "5"; return; }
    if (lower == "vbcritical")     { lastExpr_ = "16"; return; }
    if (lower == "vbquestion")     { lastExpr_ = "32"; return; }
    if (lower == "vbexclamation")  { lastExpr_ = "48"; return; }
    if (lower == "vbinformation")  { lastExpr_ = "64"; return; }
    if (lower == "vbcrlf")         { lastExpr_ = "vb6_BSTR_FromStr(L\"\\r\\n\")"; return; }
    if (lower == "vblf")           { lastExpr_ = "vb6_BSTR_FromStr(L\"\\n\")"; return; }
    if (lower == "vbcr")           { lastExpr_ = "vb6_BSTR_FromStr(L\"\\r\")"; return; }
    if (lower == "vbtab")          { lastExpr_ = "vb6_BSTR_FromStr(L\"\\t\")"; return; }
    if (lower == "vbnewline")      { lastExpr_ = "vb6_BSTR_FromStr(L\"\\r\\n\")"; return; }
    if (lower == "vbnullstring")   { lastExpr_ = "vb6_BSTR_Empty()"; return; }
    if (lower == "vbempty")        { lastExpr_ = "vb6_VariantEmpty()"; return; }
    if (lower == "vbnothing")      { lastExpr_ = "NULL"; return; }
    if (lower == "vbtrue")         { lastExpr_ = "(-1)"; return; }
    if (lower == "vbfalse")        { lastExpr_ = "0"; return; }

    // 内置函数映射 (名称 → RTL函数名)
    static const std::unordered_map<std::string, std::string> builtinFuncs = {
        {"len",      "vb6_Len"},
        {"msgbox",   "vb6_MsgBox"},
        {"inputbox", "vb6_InputBox"},
        {"format",   "vb6_Format"},
        {"cstr",     "vb6_CStr"},
        {"cint",     "vb6_CInt"},
        {"clng",     "vb6_CLng"},
        {"cdbl",     "vb6_CDbl"},
        {"csng",     "vb6_CSng"},
        {"cbool",    "vb6_CBool"},
        {"cdate",    "vb6_CDate"},
        {"cbyt",     "vb6_CByte"},
        {"instr",    "vb6_InStr"},
        {"left",     "vb6_Left"},
        {"right",    "vb6_Right"},
        {"mid",      "vb6_Mid"},
        {"trim",     "vb6_Trim"},
        {"ltrim",    "vb6_LTrim"},
        {"rtrim",    "vb6_RTrim"},
        {"ucase",    "vb6_UCase"},
        {"lcase",    "vb6_LCase"},
        {"chr",      "vb6_Chr"},
        {"asc",      "vb6_Asc"},
        {"abs",      "vb6_Abs"},
        {"int",      "vb6_Int"},
        {"fix",      "vb6_Fix"},
        {"sgn",      "vb6_Sgn"},
        {"sqr",      "vb6_Sqr"},
        {"ubound",   "vb6_UBound"},
        {"lbound",   "vb6_LBound"},
        {"isarray",  "vb6_IsArray"},
        {"isnumeric","vb6_IsNumeric"},
        {"isnothing","vb6_IsNothing"},
        {"typeof",   "vb6_TypeOf"},
        {"typename", "vb6_TypeName"},
        {"createobject","vb6_CreateObject"},
        {"getobject","vb6_GetObject"},
        // 字符串函数 (P4新增)
        {"replace",  "vb6_Replace"},
        {"space",    "vb6_Space"},
        {"string",   "vb6_String"},   // String$函数
        {"strcomp",  "vb6_StrComp"},
        {"strreverse","vb6_StrReverse"},
        {"instrrev", "vb6_InStrRev"},
        {"val",      "vb6_Val"},
        {"str",      "vb6_Str"},
        // 数学函数 (P4新增)
        {"sin",      "vb6_Sin"},
        {"cos",      "vb6_Cos"},
        {"tan",      "vb6_Tan"},
        {"atn",      "vb6_Atn"},
        {"log",      "vb6_Log"},
        {"exp",      "vb6_Exp"},
        {"round",    "vb6_Round"},
        {"rnd",      "vb6_Rnd"},
        {"randomize","vb6_Randomize"},
        // 日期时间 (P4新增)
        {"now",      "vb6_Now"},
        {"date",     "vb6_Date"},
        {"time",     "vb6_Time"},
        {"year",     "vb6_Year"},
        {"month",    "vb6_Month"},
        {"day",      "vb6_Day"},
        {"hour",     "vb6_Hour"},
        {"minute",   "vb6_Minute"},
        {"second",   "vb6_Second"},
        // 类型转换 (P4新增)
        {"cbyte",    "vb6_CByte"},
        {"cvar",     "vb6_CVar"},
        {"hex",      "vb6_Hex"},
        {"oct",      "vb6_Oct"},
        // 类型检查 (P4新增)
        {"isnull",   "vb6_IsNull"},
        {"isempty",  "vb6_IsEmpty"},
        {"isobject", "vb6_IsObject"},
        {"isdate",   "vb6_IsDate"},
        {"iserror",  "vb6_IsError"},
        {"vartype",  "vb6_VarType"},
        // 文件I/O (P4新增)
        {"freefile", "vb6_FreeFile"},
        {"eof",      "vb6_EOF"},
        {"lof",      "vb6_LOF"},
        {"loc",      "vb6_Loc"},
        {"kill",     "vb6_Kill"},
    };

    auto it = builtinFuncs.find(lower);
    if (it != builtinFuncs.end()) {
        // 无参内置函数: VB6允许省略括号(如 Now, Date, Time)
        // 当IdentifierExpr引用这些函数时，必须生成调用(带括号)
        static const std::unordered_set<std::string> zeroArgBuiltinFuncs = {
            "now", "date", "time", "freefile"
        };
        if (zeroArgBuiltinFuncs.count(lower)) {
            lastExpr_ = it->second + "()";
        } else {
            lastExpr_ = it->second;
        }
        return;
    }

    // 用户定义的过程: 加vb6_前缀
    // 查找模块级符号
    Symbol* sym = symTab_.lookupModule(node.name);
    if (sym && (sym->kind == SymbolKind::Sub || sym->kind == SymbolKind::Function
             || sym->kind == SymbolKind::DeclareSub || sym->kind == SymbolKind::DeclareFunc)) {
        // Declare函数: 使用VB6函数名的cIdent形式 (通过#define映射到导出名)
        if (sym->kind == SymbolKind::DeclareSub || sym->kind == SymbolKind::DeclareFunc) {
            lastExpr_ = cIdent(node.name);
        } else if (sym->isExternal) {
            // 跨模块函数: 使用 vb6_<ModuleName>_<ProcName> 格式
            lastExpr_ = cProcName(node.name, sym->access, sym->sourceModule);
        } else {
            lastExpr_ = cProcName(node.name, sym->access);
        }
        return;
    }

    // 外部变量/常量: 使用 vb6_<ModuleName>_<Name> 格式
    if (sym && sym->isExternal) {
        lastExpr_ = "vb6_" + cIdent(sym->sourceModule) + "_" + cName;
        return;
    }

    lastExpr_ = cName;
}

void CCodeGen::visit(BinaryExpr& node) {
    emitExpr(*node.left);
    std::string left = std::move(lastExpr_);
    emitExpr(*node.right);
    std::string right = std::move(lastExpr_);

    // 字符串连接运算: VB6 & → vb6_BSTR_Concat
    if (node.op == BinaryOp::Concat) {
        lastExpr_ = "vb6_BSTR_Concat(" + left + ", " + right + ")";
        return;
    }

    // 幂运算: VB6 ^ → pow()
    if (node.op == BinaryOp::Pow) {
        lastExpr_ = "vb6_Pow(" + left + ", " + right + ")";
        return;
    }

    // 整除: VB6 \ → vb6_IntDiv (确保整数截断)
    if (node.op == BinaryOp::IntDiv) {
        lastExpr_ = "vb6_IntDiv(" + left + ", " + right + ")";
        return;
    }

    // 等价运算: VB6 Eqv → ~(a^b)
    if (node.op == BinaryOp::Eqv) {
        lastExpr_ = "(~(" + left + " ^ " + right + "))";
        return;
    }

    // 蕴含运算: VB6 Imp → (~a | b)
    if (node.op == BinaryOp::Imp) {
        lastExpr_ = "((~" + left + ") | " + right + ")";
        return;
    }

    // Like运算: VB6 Like → vb6_Like
    if (node.op == BinaryOp::Like) {
        lastExpr_ = "vb6_Like(" + left + ", " + right + ")";
        return;
    }

    std::string op = mapBinaryOp(node.op);

    // VB6的And/Or/Not是逻辑运算也是位运算（取决于操作数类型）
    // 简化处理: 直接映射为C位运算, VB6语义兼容
    lastExpr_ = "(" + left + " " + op + " " + right + ")";
}

void CCodeGen::visit(UnaryExpr& node) {
    emitExpr(*node.operand);
    std::string operand = std::move(lastExpr_);

    switch (node.op) {
        case UnaryOp::Negate:
            lastExpr_ = "(-" + operand + ")";
            break;
        case UnaryOp::Not:
            // VB6 Not = 位取反 (C: ~)
            lastExpr_ = "(~" + operand + ")";
            break;
    }
}

void CCodeGen::visit(MemberAccessExpr& node) {
    // 内置对象方法: Debug.Print → vb6_DebugPrint
    // 检查 object 是否是 IdentifierExpr
    if (node.object && node.object->kind == ASTNodeKind::IdentifierExpr) {
        auto& objIdent = static_cast<IdentifierExpr&>(*node.object);
        std::string objLower = objIdent.name;
        std::transform(objLower.begin(), objLower.end(), objLower.begin(), ::tolower);
        std::string memLower = node.memberName;
        std::transform(memLower.begin(), memLower.end(), memLower.begin(), ::tolower);

        if (objLower == "debug" && memLower == "print") {
            lastExpr_ = "vb6_DebugPrint";
            return;
        }
        if (objLower == "debug" && memLower == "assert") {
            lastExpr_ = "vb6_DebugAssert";
            return;
        }
    }

    // 通用成员访问
    emitExpr(*node.object);
    std::string obj = std::move(lastExpr_);
    lastExpr_ = obj + "." + cIdent(node.memberName);
}

void CCodeGen::visit(DictionaryAccessExpr& node) {
    emitExpr(*node.object);
    std::string obj = std::move(lastExpr_);
    // obj!key → 字典访问, 暂用函数调用
    lastExpr_ = "vb6_DictAccess(" + obj + ", L\"" + node.key + "\")";
}

void CCodeGen::visit(IndexOrCallExpr& node) {
    // 检测数组访问: arr(i) — callee 是 IdentifierExpr 且在已知数组集合中
    // VB6 不区分数组索引和函数调用, 统一为 IndexOrCallExpr
    bool isArrayAccess = false;
    std::string arrName;
    Vb6Type arrElemType = Vb6Type::Variant;

    if (node.callee && node.callee->kind == ASTNodeKind::IdentifierExpr && node.named.empty()) {
        auto& ident = static_cast<IdentifierExpr&>(*node.callee);
        std::string lower = ident.name;
        std::transform(lower.begin(), lower.end(), lower.begin(), ::tolower);

        // 先查已知数组集合 (cgen过程中维护)
        if (knownArrays_.count(lower)) {
            isArrayAccess = true;
            arrName = cIdent(ident.name);
            arrElemType = arrayElemTypes_[lower];
        } else {
            // 再查符号表 (模块级数组)
            Symbol* sym = symTab_.lookupModule(ident.name);
            if (sym && sym->kind == SymbolKind::Variable && sym->isArray) {
                isArrayAccess = true;
                arrName = cIdent(ident.name);
                arrElemType = sym->type;
            }
        }
    }

    if (isArrayAccess) {
        // 数组元素访问: arr(i) → VB6_SA_AT(type, arr, i)
        emitExpr(*node.callee);
        std::string callee = std::move(lastExpr_);

        // 参数: 只取第一个位置参数作为索引 (一维)
        std::string index = "0";
        if (!node.positional.empty()) {
            emitExpr(*node.positional[0]);
            index = std::move(lastExpr_);
        }

        std::string elemCType = mapSaElemCType(arrElemType);
        lastExpr_ = "VB6_SA_AT(" + elemCType + ", " + arrName + ", " + index + ")";
        return;
    }

    // 函数调用路径 (原有逻辑)
    emitExpr(*node.callee);
    std::string callee = std::move(lastExpr_);

    // 如果callee已经是func()形式(无参内置函数调用如vb6_Now())，
    // 需要拆开重组为func(args)，因为IndexOrCallExpr表示带参数调用
    bool calleeIsZeroArgCall = false;
    if (callee.size() >= 2 && callee.substr(callee.size() - 2) == "()") {
        calleeIsZeroArgCall = true;
        callee = callee.substr(0, callee.size() - 2);
    }

    // 位置参数
    std::vector<std::string> args;
    for (auto& arg : node.positional) {
        emitExpr(*arg);
        args.push_back(std::move(lastExpr_));
    }

    // 命名参数暂按位置展开(TODO: 按参数名映射)
    for (auto& named : node.named) {
        emitExpr(*named.value);
        args.push_back(std::move(lastExpr_));
    }

    // 构造调用
    std::string argList;
    for (size_t i = 0; i < args.size(); i++) {
        if (i > 0) argList += ", ";
        argList += args[i];
    }

    // 特殊处理: UBound/LBound 缺省维度参数时补1
    if ((callee == "vb6_UBound" || callee == "vb6_LBound") && args.size() == 1) {
        argList += ", 1";
    }

    lastExpr_ = callee + "(" + argList + ")";
}

