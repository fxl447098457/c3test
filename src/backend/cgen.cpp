void CodeEmitter::emitLine(const std::string& line) {
    for (int i = 0; i < indentLevel_; i++) {
        oss_ << "    ";  // 4空格缩进
    }
    oss_ << line << "\n";
}

void CodeEmitter::emit(const std::string& text) {
    oss_ << text;
}

void CodeEmitter::emitBlank() {
    oss_ << "\n";
}

